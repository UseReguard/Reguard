PROMPT_TEMPLATE = """You are classifying EU AI compliance obligations by their detection method — how compliance can be VERIFIED in practice.

## Detection methods

- "code":    Verifiable by reading source code alone. No external system needed.
             Examples: must display a notice; must have a human override button; must expose a deletion endpoint.
- "api":     Verifiable by querying an external integration alone. The source code is irrelevant.
             Examples: MFA enabled on AWS IAM; encryption-at-rest on S3; SBOM generated by Dependabot.
- "hybrid":  STRICT REQUIREMENT: verification fails if EITHER code OR API evidence is missing.
             Both code evidence (the function/feature exists in source) AND API evidence (it is actively being used/configured) must be present.
             Use "hybrid" ONLY when neither alone is sufficient — when you genuinely cannot tell if the requirement is met without checking both.
- "process": Cannot be auto-detected at all. Requires human attestation of a document, governance step, or organisational practice.
             Examples: risk assessment docs, board approval, training records, internal policies.

## Critical rule for "hybrid"

The LEAST-INCLUSIVE interpretation wins. Ask:
1. Can I verify this purely by reading source? → code
2. Can I verify this purely by querying an external system? → api
3. Is there any way to verify without code? → not hybrid (probably code or api)
4. Is there any way to verify without an external system? → not hybrid (probably code or process)
5. Is verification TRULY impossible without BOTH? → hybrid

Default to code/api/process when in doubt. "Hybrid" is the narrowest, most specific category.

## Examples

| Requirement | Method | Why |
|---|---|---|
| "Providers shall inform natural persons that they are interacting with an AI system" (AI Act Art. 50) | code | Source must render a notice — no API needed |
| "The provider shall implement a risk management system" (AI Act Art. 9) | process | Documented QMS — neither code nor API verifies it |
| "Personal data shall be encrypted at rest" (GDPR Art. 32) | api | Verified by querying infra (AWS KMS) — source code is irrelevant |
| "Multi-factor authentication shall be enabled" | api | Verified via Okta/AWS IAM |
| "Human oversight shall be effective" (AI Act Art. 14) | hybrid | Without the code gate, oversight can't exist; without the audit log API, you can't tell if it's actually used |
| "The organisation shall conduct annual risk assessments" | process | Documented risk register |
| "Logs shall be kept for 6 months" | hybrid | Code generates logs, but only storage API proves retention |
| "A vulnerability disclosure policy shall be published" (CRA) | process | Public document — neither code nor API verifies |
| "The system shall allow data subjects to request deletion" (GDPR Art. 17) | code | Source exposes an endpoint |
| "Threat intelligence shall be collected and used" (ISO A.5.7) | process | What matters is the documented intelligence process; tools don't verify it |
| "Configuration management shall be implemented" (ISO A.8.9) | process | Documented config mgmt process; tools support but don't verify it |
| "Cryptography shall be used to protect information" (ISO A.8.24) | api | Verified by querying what's actually encrypted (storage config) |
| "Secure coding standards shall be established" (ISO A.8.28) | process | Standards are documented; tools (linters) only flag violations, not prove compliance |
| "Change management shall be controlled" (ISO A.8.32) | process | The process is documented; tools help but don't verify |
| "AI system requirements shall be documented" (ISO A.6.2.2) | process | Documentation requirement |
| "Network security controls shall be configured" (PCI 1.1) | hybrid | Config in code/IaC, but compliance needs runtime verification |

## Output format

Respond with ONLY this JSON (no prose):
{{"method": "code|api|hybrid|process", "confidence": 0.0-1.0, "reasoning": "<one sentence>"}}

## Requirement to classify

Framework: {framework_name} ({framework_id})
Code: {code}
Title: {title}

Text:
\"\"\"
{content}
\"\"\"

JSON:
"""


def call_ollama(prompt: str, model: str = DEFAULT_MODEL, timeout: int = 60) -> dict:
    """Call local Ollama with structured JSON output."""
    try:
        r = requests.post(
            OLLAMA_URL,
            json={
                "model": model,
                "prompt": prompt,
                "format": "json",
                "stream": False,
                "options": {"temperature": 0.1},  # low temp for consistency
            },
            timeout=timeout,
        )
        r.raise_for_status()
        return json.loads(r.json()["response"])
    except Exception as e:
        return {"method": "process", "confidence": 0.0, "reasoning": f"OLLAMA ERROR: {e}"}


def classify_item(
    framework_id: str,
    framework_name: str,
    code: str,
    title: str,
    content: str,
    model: str = DEFAULT_MODEL,
    max_chars: int = 1500,
) -> dict:
    """Classify a single item via Ollama."""
    if len(content) > max_chars:
        content = content[:max_chars] + "…"
    prompt = PROMPT_TEMPLATE.format(
        framework_name=framework_name,
        framework_id=framework_id,
        code=code,
        title=title or "(no title)",
        content=content or "(no content)",
    )
    return call_ollama(prompt, model=model)


