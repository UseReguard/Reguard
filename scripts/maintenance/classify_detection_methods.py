def fetch_items(session, batch: list[tuple]) -> list[dict]:
    """Resolve batch tuples into items with their content.

    Accepts both 3-tuple (source, fw_id, code) and 5-tuple
    (source, fw_id, code, expected_method, note) — for validation mode.
    """
    items = []
    for entry in batch:
        # Unpack with optional expected_method + note (5-tuple)
        if len(entry) == 5:
            source, fw_id, code, expected_method, note = entry
        else:
            source, fw_id, code = entry
            expected_method = None
            note = None

        if source == "law":
            # Articles are stored with all sub-clauses flattened in one row,
            # so match by prefix (article_number LIKE '5%' matches '5', '5(a)(b)...', etc.)
            row = session.execute(
                select(LawArticle, Law)
                .join(Law, LawArticle.celex == Law.celex)
                .where(
                    LawArticle.celex == fw_id,
                    LawArticle.article_number.like(f"{code}%"),
                )
                .order_by(LawArticle.article_number)
            ).first()
            if not row:
                log.warning(f"  ⚠ Not found: law {fw_id} art. {code}")
                continue
            art, law = row
            items.append({
                "source": "law",
                "id": art.id,
                "framework_id": fw_id,
                "framework_name": law.short_name or law.long_name,
                "code": f"Article {art.article_number}",
                "title": art.title,
                "content": art.text,
                "expected_method": expected_method,
                "note": note,
            })
        else:  # framework
            row = session.execute(
                select(FrameworkItem, Framework)
                .join(Framework, FrameworkItem.framework_id == Framework.id)
                .where(FrameworkItem.framework_id == fw_id, FrameworkItem.code == code)
            ).first()
            if not row:
                log.warning(f"  ⚠ Not found: framework {fw_id} item {code}")
                continue
            item, fw = row
            items.append({
                "source": "framework",
                "id": item.id,
                "framework_id": fw_id,
                "framework_name": fw.name,
                "code": item.code,
                "title": item.title,
                "content": item.content,
                "expected_method": expected_method,
                "note": note,
            })
    return items


def write_to_db(session, item: dict, classification: dict, dry_run: bool = False) -> None:
    """Persist classification to DB."""
    if dry_run:
        return
    if item["source"] == "law":
        art = session.get(LawArticle, item["id"])
    else:
        art = session.get(FrameworkItem, item["id"])

    art.detection_method = classification["method"]
    art.detection_confidence = classification.get("confidence")
    art.detection_classified_by = "llm"
    art.detection_reasoning = classification.get("reasoning", "")[:1000]
    art.detection_reviewed_at = datetime.utcnow()


def run_full(
    model: str = DEFAULT_MODEL,
    batch_size: int = 50,
    min_content_chars: int = 50,
    limit: int | None = None,
) -> dict:
    """Classify ALL unclassified items in the database.

    - Skips items already classified (detection_classified_by IS NOT NULL)
    - Skips items with content shorter than min_content_chars
    - Commits every batch_size items for resumability
    - Logs progress to stderr
    """
    init_db()
    started = time.time()
    stats = {
        "law_articles": 0,
        "framework_items": 0,
        "skipped_short": 0,
        "already_done": 0,
        "method_counts": {},
        "avg_confidence": 0.0,
        "low_confidence": 0,
    }

    def process_batch(items: list[dict]) -> None:
        for item in items:
            classification = classify_item(
                framework_id=item["framework_id"],
                framework_name=item["framework_name"],
                code=item["code"],
                title=item["title"],
                content=item["content"],
                model=model,
            )
            method = classification.get("method", "process")
            conf = classification.get("confidence", 0.0)

            if item["source"] == "law":
                row = session.get(LawArticle, item["id"])
                stats["law_articles"] += 1
            else:
                row = session.get(FrameworkItem, item["id"])
                stats["framework_items"] += 1

            row.detection_method = method
            row.detection_confidence = conf
            row.detection_classified_by = "llm"
            row.detection_reasoning = classification.get("reasoning", "")[:1000]
            row.detection_reviewed_at = datetime.utcnow()

            stats["method_counts"][method] = stats["method_counts"].get(method, 0) + 1
            if conf < 0.7:
                stats["low_confidence"] += 1

        # Commit this batch
        session.commit()

    with session_scope() as session:
        # Fetch all law_articles that need classification
        law_rows = session.execute(
            select(LawArticle, Law)
            .join(Law, LawArticle.celex == Law.celex)
            .where(
                LawArticle.detection_classified_by.is_(None),
                LawArticle.text.isnot(None),
            )
            .order_by(LawArticle.celex, LawArticle.id)
        ).all()

        # Fetch all framework_items that need classification
        fw_rows = session.execute(
            select(FrameworkItem, Framework)
            .join(Framework, FrameworkItem.framework_id == Framework.id)
            .where(
                FrameworkItem.detection_classified_by.is_(None),
                FrameworkItem.content.isnot(None),
            )
            .order_by(FrameworkItem.framework_id, FrameworkItem.id)
        ).all()

        # Convert to unified item dicts
        all_items: list[dict] = []
        for art, law in law_rows:
            if not art.text or len(art.text) < min_content_chars:
                stats["skipped_short"] += 1
                continue
            all_items.append({
                "source": "law",
                "id": art.id,
                "framework_id": law.celex,
                "framework_name": law.short_name or law.long_name,
                "code": f"Article {art.article_number}",
                "title": art.title,
                "content": art.text,
            })

        for item, fw in fw_rows:
            if not item.content or len(item.content) < min_content_chars:
                stats["skipped_short"] += 1
                continue
            all_items.append({
                "source": "framework",
                "id": item.id,
                "framework_id": fw.id,
                "framework_name": fw.name,
                "code": item.code,
                "title": item.title,
                "content": item.content,
            })

        if limit:
            all_items = all_items[:limit]

        total = len(all_items)
        log.info(f"Classifying {total} items ({stats['skipped_short']} skipped for short content)")
        log.info(f"  Law articles: {stats['law_articles']} to do")
        log.info(f"  Framework items: {stats['framework_items']} to do")
        log.info(f"  Model: {model}")
        log.info(f"  Batch size: {batch_size}\n")

        # Process in batches with progress logging
        for batch_start in range(0, total, batch_size):
            batch_end = min(batch_start + batch_size, total)
            batch = all_items[batch_start:batch_end]

            t0 = time.time()
            process_batch(batch)
            elapsed = time.time() - t0
            per_item = elapsed / len(batch) if batch else 0
            eta_total_sec = per_item * (total - batch_end)
            eta_min = eta_total_sec / 60

            log.info(
                f"  [{batch_end:4d}/{total}] "
                f"batch={len(batch):3d} "
                f"elapsed={elapsed:5.1f}s "
                f"per_item={per_item:.2f}s "
                f"ETA={eta_min:.1f}min "
                f"methods={stats['method_counts']}"
            )

        # Log audit
        session.add(ReviewAction(
            celex="classification_full",
            action="full_classification",
            reason=(
                f"Classified {stats['law_articles']} law articles + "
                f"{stats['framework_items']} framework items with {model}"
            ),
            actor="classify_detection_methods",
        ))
        session.commit()

    total_done = stats["law_articles"] + stats["framework_items"]
    total_elapsed = time.time() - started
    log.info(f"\n=== Full classification complete ===")
    log.info(f"  Total classified: {total_done}")
    log.info(f"  Skipped (short content): {stats['skipped_short']}")
    log.info(f"  Total elapsed: {total_elapsed/60:.1f}min")
    log.info(f"  Method distribution: {stats['method_counts']}")

    return stats


def run_test_batch(model: str = DEFAULT_MODEL, dry_run: bool = False) -> dict:
    """Run classification on the test batch."""
    init_db()
    stats = {
        "results": [],
        "method_counts": {},
        "avg_confidence": 0.0,
        "low_confidence": [],
    }

    with session_scope() as session:
        items = fetch_items(session, TEST_BATCH)
        log.info(f"Loaded {len(items)}/{len(TEST_BATCH)} items from test batch\n")

        for i, item in enumerate(items, 1):
            t0 = time.time()
            classification = classify_item(
                framework_id=item["framework_id"],
                framework_name=item["framework_name"],
                code=item["code"],
                title=item["title"],
                content=item["content"],
                model=model,
            )
            elapsed = time.time() - t0

            result = {
                **item,
                "classification": classification,
                "elapsed_s": round(elapsed, 1),
            }
            stats["results"].append(result)

            method = classification.get("method", "unknown")
            conf = classification.get("confidence", 0)
            stats["method_counts"][method] = stats["method_counts"].get(method, 0) + 1

            if conf < 0.7:
                stats["low_confidence"].append(result)

            write_to_db(session, item, classification, dry_run=dry_run)

            # Inline progress
            conf_icon = "🟢" if conf >= 0.7 else "🟡" if conf >= 0.4 else "🔴"
            content_preview = (item["content"] or "")[:60].replace("\n", " ")
            log.info(
                f"  [{i:2d}/{len(items)}] {conf_icon} {method:7s} ({conf:.2f}) "
                f"{item['framework_id']:15s} {item['code']:15s} — "
                f"{content_preview}…"
            )

        # Log review action
        session.add(ReviewAction(
            celex="classification_test",
            action="test_classification",
            reason=f"Classified {len(items)} items with {model}",
            actor="classify_detection_methods",
        ))

    confidences = [r["classification"].get("confidence", 0) for r in stats["results"]]
    stats["avg_confidence"] = round(sum(confidences) / len(confidences), 3) if confidences else 0

    return stats


def run_validation(model: str = DEFAULT_MODEL, dry_run: bool = True) -> dict:
    """Run validation batch and compute accuracy against expected classifications."""
    init_db()
    stats = {
        "results": [],
        "correct": 0,
        "wrong": 0,
        "by_method": {},
        "confusion": {},  # (expected → actual) counts
        "errors": [],
    }

    with session_scope() as session:
        items = fetch_items(session, VALIDATION_BATCH)
        items = [i for i in items if i.get("expected_method")]  # skip not-found
        log.info(f"Loaded {len(items)}/{len(VALIDATION_BATCH)} items from validation batch\n")

        for i, item in enumerate(items, 1):
            t0 = time.time()
            classification = classify_item(
                framework_id=item["framework_id"],
                framework_name=item["framework_name"],
                code=item["code"],
                title=item["title"],
                content=item["content"],
                model=model,
            )
            elapsed = time.time() - t0

            actual = classification.get("method", "?")
            expected = item["expected_method"]
            correct = (actual == expected)

            result = {
                **item,
                "classification": classification,
                "actual": actual,
                "expected": expected,
                "correct": correct,
                "elapsed_s": round(elapsed, 1),
            }
            stats["results"].append(result)

            if correct:
                stats["correct"] += 1
            else:
                stats["wrong"] += 1
                confusion_key = f"{expected}→{actual}"
                stats["confusion"][confusion_key] = stats["confusion"].get(confusion_key, 0) + 1

            # Track per-method accuracy
            for m in (expected, actual):
                stats["by_method"].setdefault(m, {"correct": 0, "total": 0})
                stats["by_method"][m]["total"] += 1
            if correct:
                stats["by_method"][expected]["correct"] += 1

            icon = "✅" if correct else "❌"
            conf = classification.get("confidence", 0)
            log.info(
                f"  [{i:2d}/{len(items)}] {icon} {actual:7s} (expected {expected:7s}, conf={conf:.2f}) "
                f"{item['framework_id'][:18]:18s} {item['code'][:18]:18s}"
            )

        # Log review action
        session.add(ReviewAction(
            celex="validation",
            action="validation_run",
            reason=f"Validated {len(items)} items with {model}",
            actor="classify_detection_methods",
        ))

    stats["accuracy"] = round(stats["correct"] / len(items), 3) if items else 0
    return stats


def print_validation_report(stats: dict) -> None:
    """Print validation results with confusion matrix."""
    n = len(stats["results"])
    print("\n" + "=" * 100)
    print(f"VALIDATION RESULTS — {stats['correct']}/{n} correct ({stats['accuracy']*100:.1f}%)")
    print("=" * 100)

    # Per-method accuracy
    print("\nAccuracy by expected method:")
    print(f"  {'Method':10s} {'Correct':8s} {'Total':6s} {'Accuracy':10s}")
    for method in sorted(stats["by_method"]):
        m = stats["by_method"][method]
        acc = m["correct"] / m["total"] if m["total"] else 0
        print(f"  {method:10s} {m['correct']:8d} {m['total']:6d} {acc*100:6.1f}%")

    # Confusion matrix
    if stats["confusion"]:
        print("\nConfusion (expected → actual):")
        for k, v in sorted(stats["confusion"].items(), key=lambda x: -x[1]):
            print(f"  {k:25s}  {'█' * v}  {v}")

    # Disagreements
    print("\n" + "-" * 100)
    print(f"{'Actual':8s} {'Expected':9s} {'Framework':30s} {'Code':25s} Reasoning")
    print("-" * 100)
    for r in stats["results"]:
        if r["correct"]:
            continue
        actual = r["actual"]
        expected = r["expected"]
        reasoning = r["classification"].get("reasoning", "")[:80]
        print(
            f"{actual:8s} {expected:9s} "
            f"{r['framework_name'][:30]:30s} {r['code'][:25]:25s} {reasoning}"
        )

    # Verdict
    print("\n" + "=" * 100)
    if stats["accuracy"] >= 0.9:
        verdict = "✅ PASS — accuracy ≥90%, safe to scale to all items"
    elif stats["accuracy"] >= 0.8:
        verdict = "⚠️  MARGINAL — accuracy 80-90%, review disagreements before scaling"
    else:
        verdict = "❌ FAIL — accuracy <80%, prompt needs tuning"
    print(verdict)
    print("=" * 100)


def print_report(stats: dict) -> None:
    """Pretty-print classification results."""
    print("\n" + "=" * 100)
    print("CLASSIFICATION RESULTS")
    print("=" * 100)

    # Summary
    print(f"\nMethod distribution:")
    for method, count in sorted(stats["method_counts"].items()):
        print(f"  {method:8s}  {'█' * count} {count}")
    print(f"\nAverage confidence: {stats['avg_confidence']}")
    print(f"Low-confidence items (<0.7): {len(stats['low_confidence'])}")

    # Detailed table
    print("\n" + "-" * 100)
    print(f"{'Method':8s} {'Conf':5s} {'Framework':30s} {'Code':25s} Reasoning")
    print("-" * 100)
    for r in stats["results"]:
        method = r["classification"].get("method", "?")
        conf = r["classification"].get("confidence", 0)
        reasoning = r["classification"].get("reasoning", "")[:80]
        print(
            f"{method:8s} {conf:5.2f} "
            f"{r['framework_name'][:30]:30s} {r['code'][:25]:25s} {reasoning}"
        )

    # Low-confidence items
    if stats["low_confidence"]:
        print("\n" + "=" * 100)
        print("LOW CONFIDENCE — needs human review:")
        print("=" * 100)
        for r in stats["low_confidence"]:
            print(f"\n  {r['framework_name']} {r['code']}")
            print(f"  Content: {(r['content'] or '')[:200]}…")
            print(f"  LLM said: {r['classification']}")


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--test", action="store_true", help="Run small test batch (default)")
    p.add_argument("--validate", action="store_true", help="Run 50-item validation against expected answers")
    p.add_argument("--batch-size", type=int, default=50, help="Commit batch size (default 50)")
    p.add_argument("--full", action="store_true", help="Classify all unclassified items")
    p.add_argument("--limit", type=int, help="Classify first N items")
    p.add_argument("--dry-run", action="store_true", help="Don't write to DB")
    p.add_argument("--model", default=DEFAULT_MODEL, help=f"Ollama model (default: {DEFAULT_MODEL})")
    args = p.parse_args()

    if args.full:
        stats = run_full(model=args.model, batch_size=args.batch_size, limit=args.limit)
        return

    if args.validate:
        stats = run_validation(model=args.model, dry_run=True)
        print_validation_report(stats)
        return

    stats = run_test_batch(model=args.model, dry_run=args.dry_run)
    print_report(stats)


if __name__ == "__main__":
    main()
